/// The method is Node's `session.configure` or `session.read`: an interactive call.
pub(crate) fn is_session_action(method: &str) -> bool {
    CONFIGURE_ACTIONS.contains(&method) || READ_ACTIONS.contains(&method) || NAMED_DIFFERENTLY.contains(&method)
}
