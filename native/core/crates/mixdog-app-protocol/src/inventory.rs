//! The inventory map (DS §18 `operations.map`): every 1.4.5 desktop
//! operation, DesktopService method, phone method and session action, and
//! its one target in protocol 2. Checked by DS-ALL-1 and DS-DUP-1.

/// Inventory list of a 1.4.5 name.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub enum InventoryList {
    /// The 166 desktop operations.
    Operations,
    /// The 61 DesktopService methods.
    Services,
    /// The 190 phone methods.
    Remote,
    /// The 303 session actions.
    Actions,
}

/// Where a 1.4.5 name went.
#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize)]
#[serde(tag = "kind", content = "target", rename_all = "camelCase")]
pub enum Target {
    /// A client method.
    Method(&'static str),
    /// Several client methods (one per former sub-action).
    Methods(&'static [&'static str]),
    /// A pushed section (read through the feed snapshot).
    Section(&'static str),
    /// A server notification.
    Notification(&'static str),
    /// A client notification.
    ClientNotification(&'static str),
    /// The response to a server request.
    ServerRequestResponse(&'static str),
    /// A core → host server request.
    HostRequest(&'static str),
    /// An X17 binary media frame of the named purpose.
    MediaFrame(&'static str),
    /// A field of the `initialize` result.
    InitializeField(&'static str),
    /// Removed by design; the reason names its replacement.
    ByDesign(&'static str),
    /// Becomes a core-internal call with no wire form.
    Internal(&'static str),
    /// Deleted (DS §17).
    Deleted(&'static str),
}

