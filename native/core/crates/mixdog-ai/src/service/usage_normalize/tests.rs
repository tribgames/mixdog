const NOW: i64 = 1_800_000_000_000;

#[test]
fn reset_moments_read_iso_seconds_millis_and_relative() {
    let s = |v: &str| Value::String(v.into());
    assert_eq!(reset_at_ms(Some(&s("2030-01-02T03:04:05Z")), None, NOW), Some(1_893_553_445_000.0));
    assert_eq!(reset_at_ms(Some(&Value::from(1_900_000_000)), None, NOW), Some(1_900_000_000_000.0));
    assert_eq!(reset_at_ms(Some(&Value::from(1_900_000_000_000_i64)), None, NOW), Some(1_900_000_000_000.0));
    assert_eq!(reset_at_ms(None, Some(&Value::from(60)), NOW), Some(NOW as f64 + 60_000.0));
    assert_eq!(reset_at_ms(Some(&s("soon")), None, NOW), None);
}

#[test]
fn grok_billing_reads_credit_totals_and_unified_percent() {
    let totals = serde_json::json!({"currentPeriod": {"type": "USAGE_PERIOD_TYPE_WEEKLY", "end": 1_900_000_000},
        "weeklyLimit": {"val": 200}, "used": {"val": 50}});
    let w = credit_window_from_billing(&totals, NOW).unwrap();
    assert_eq!(
        w.to_string(),
        r#"{"label":"W","source":"grok-build-billing","usedPct":25,"usedCredits":50,"limitCredits":200,"remainingCredits":150,"resetAt":1900000000000}"#
    );
    let unified = serde_json::json!({"isUnifiedBillingUser": true, "currentPeriod": {"type": "USAGE_PERIOD_TYPE_MONTHLY"}, "creditUsagePercent": {"val": 140}});
    assert_eq!(
        credit_window_from_billing(&unified, NOW).unwrap().to_string(),
        r#"{"label":"M","source":"grok-build-billing","usedPct":100}"#
    );
    assert!(credit_window_from_billing(&serde_json::json!({"x": 1}), NOW).is_none());
    // Node throws on an absent, blank or non-string period type, whatever else the answer holds.
    for typeless in [
        serde_json::json!({"isUnifiedBillingUser": true}),
        serde_json::json!({"currentPeriod": {"type": "  "}, "monthlyLimit": 100, "used": 5}),
        serde_json::json!({"currentPeriod": {"type": 7}, "monthlyLimit": 100, "used": 5}),
    ] {
        assert!(credit_window_from_billing(&typeless, NOW).is_none(), "{typeless}");
    }
    // `currentPeriod?.type ?? current_period?.type`: a period without a type defers to the other spelling.
    let deferred = serde_json::json!({"currentPeriod": {"end": 1_900_000_000}, "current_period": {"type": "USAGE_PERIOD_TYPE_WEEKLY"}, "weeklyLimit": 10, "used": 1});
    assert_eq!(credit_window_from_billing(&deferred, NOW).unwrap()["label"], "W");    let cap = serde_json::json!({"currentPeriod": {"type": "OTHER"}, "onDemandCap": {"val": 10}, "onDemandUsed": 4, "billingPeriodStart": "2030-01-01T00:00:00Z", "billingPeriodEnd": "2030-01-08T00:00:00Z"});
    assert_eq!(
        balance_from_grok_billing(&cap, NOW).to_string(),
        r#"{"source":"grok-build-on-demand","period":"weekly","budgetCredits":10,"spentCredits":4,"remainingCredits":6}"#
    );
}

#[test]
fn reset_credit_offer_has_a_stable_revision() {
    let detail = serde_json::json!({"credits": [
        {"status": "Available", "expires_at": 1_900_000_500, "granted_at": 1_800_000_000},
        {"status": "available", "expires_at": 1_900_000_100},
        {"status": "used"}]});
    let embedded = serde_json::json!({"available_count": 2, "next_expires_at": 1_900_000_100});
    let a = normalize_codex_reset_credits(Some(&detail), "acct", NOW).unwrap();
    let b = normalize_codex_reset_credits(Some(&embedded), "acct", NOW).unwrap();
    assert_eq!(a["offerRevision"], b["offerRevision"]);
    assert_eq!(a["availableCount"], 2);
    assert_eq!(a["availableCredits"][0]["expiresAt"], 1_900_000_100_000_i64);
    assert!(a["offerRevision"].as_str().unwrap().starts_with("v1:"));
    assert!(normalize_codex_reset_credits(Some(&serde_json::json!({})), "acct", NOW).is_none());
}


/// Node's recorded outputs (`tests/golden/usage/normalize.json`, generated by
/// calling `normalizeOpenAIWhamUsage` / `normalizeAnthropicUsage`).
#[cfg(node_twin)]
#[test]
fn matches_the_recorded_node_outputs() {
    let text = include_str!("../../../tests/golden/usage/normalize.json");
    let cases: Vec<Value> = serde_json::from_str(text).unwrap();
    assert_eq!(cases.len(), 10);
    for case in cases {
        let name = case["name"].as_str().unwrap();
        let got = match case["fn"].as_str().unwrap() {
            "wham" => normalize_openai_wham_usage(&case["input"], NOW),
            _ => normalize_anthropic_usage(&case["input"], "anthropic-oauth", NOW),
        };
        let want = if case["output"].is_null() { None } else { Some(case["output"].clone()) };
        assert_eq!(got.map(|v| v.to_string()), want.map(|v| v.to_string()), "{name}");
    }
}

