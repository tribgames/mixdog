//! The one table of image file extensions and what is known of each: its media type, whether every model provider takes
//! it, whether a web browser draws it, whether it is markup (which a viewer may run). The codec's [`Format`] is its
//! source; a few types the codec does not decode (BMP, ICO, HEIC) are listed beside it so a desktop preview or open
//! rule has every image extension fact in one place. The desktop's `apps/desktop/src/shared/image-types.generated.ts`
//! is rendered from it by [`typescript`], and a test fails when the file differs.

use crate::decode::Format;

/// One file extension of an image type.
#[derive(Clone, PartialEq, Eq, Debug)]
pub struct ImageType {
    /// Lower case, without the dot.
    pub extension: &'static str,
    pub media_type: &'static str,
    /// Every model provider takes this type as an image (PNG, JPEG, GIF, WebP).
    pub provider_takes: bool,
    pub browser_draws: bool,
    /// Markup a handler may run (SVG).
    pub markup: bool,
    /// The extension a file of this type is written with.
    pub primary: bool,
}

/// Every image extension: the codec's formats, then the types it does not decode.
pub fn image_types() -> Vec<ImageType> {
    let mut types = Vec::new();
    for format in Format::ALL {
        for (index, dotted) in format.extensions().iter().enumerate() {
            types.push(ImageType {
                extension: &dotted[1..],
                media_type: format.media_type(),
                provider_takes: format.carried_as() == format,
                browser_draws: format.browsers_draw(),
                markup: format == Format::Svg,
                primary: index == 0,
            });
        }
    }
    for (extension, media_type, browser_draws) in [("bmp", "image/bmp", true), ("ico", "image/x-icon", true), ("heic", "image/heic", false)] {
        types.push(ImageType { extension, media_type, provider_takes: false, browser_draws, markup: false, primary: true });
    }
    types
}

/// The TypeScript module the desktop reads the table from.
pub fn typescript() -> String {
    let mut out = String::from(
        "// Generated by `mixdog_imaging::format_table::typescript` from the codec's `Format` table; do not edit.\n\
         // The Rust test `the_desktop_image_table_is_rendered_from_the_codec` (mixdog-imaging/tests/features.rs) fails when this file differs.\n\
         \n\
         export interface ImageType {\n\
         \x20 readonly extension: string;\n\
         \x20 readonly mime: string;\n\
         \x20 /** Every model provider takes this type as an image. */\n\
         \x20 readonly providerTakes: boolean;\n\
         \x20 readonly browserDraws: boolean;\n\
         \x20 /** Markup a handler may run. */\n\
         \x20 readonly markup: boolean;\n\
         \x20 /** The extension a file of this type is written with. */\n\
         \x20 readonly primary: boolean;\n\
         }\n\
         \n\
         export const IMAGE_TYPES: readonly ImageType[] = [\n",
    );
    for t in image_types() {
        out.push_str(&format!(
            "  {{ extension: '{}', mime: '{}', providerTakes: {}, browserDraws: {}, markup: {}, primary: {} }},\n",
            t.extension, t.media_type, t.provider_takes, t.browser_draws, t.markup, t.primary
        ));
    }
    out.push_str("];\n");
    out
}
