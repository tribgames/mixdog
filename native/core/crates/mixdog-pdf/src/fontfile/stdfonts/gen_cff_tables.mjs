// Writes cff_tables.rs: the CFF standard strings and the predefined charsets of pdf.js 6.4.299 (src/core/cff_parser.js,
// src/core/charsets.js). Usage: node gen_cff_tables.mjs <path of pdfjs-dist legacy/build/pdf.worker.mjs> <output .rs>
import { readFileSync, writeFileSync } from "node:fs";

const [, , workerPath, outPath] = process.argv;
const text = readFileSync(workerPath, "utf8");

function table(name) {
  const start = text.indexOf(`\nconst ${name} = [`);
  if (start < 0) throw new Error(`${name} not found`);
  const from = text.indexOf("[", start);
  const end = text.indexOf("];\n", from);
  return JSON.parse(text.slice(from, end + 1));
}

const out = [
  "// Generated by gen_cff_tables.mjs from pdfjs-dist 6.4.299 (legacy/build/pdf.worker.mjs); do not edit.",
  "//! The CFF standard strings and the predefined charsets (pdf.js `CFFStandardStrings`, `ISOAdobeCharset`,",
  "//! `ExpertCharset`, `ExpertSubsetCharset`).",
  "",
];
for (const [rust, js, doc] of [
  ["CFF_STANDARD_STRINGS", "CFFStandardStrings", "the 391 standard strings (SID 0 to 390)"],
  ["ISO_ADOBE_CHARSET", "ISOAdobeCharset", "predefined charset 0"],
  ["EXPERT_CHARSET", "ExpertCharset", "predefined charset 1"],
  ["EXPERT_SUBSET_CHARSET", "ExpertSubsetCharset", "predefined charset 2"],
]) {
  const names = table(js);
  out.push(`/// pdf.js \`${js}\`: ${doc}.`);
  out.push(`pub static ${rust}: [&str; ${names.length}] = [`);
  for (const n of names) out.push(`    ${JSON.stringify(n)},`);
  out.push("];", "");
}
writeFileSync(outPath, out.join("\n"));
