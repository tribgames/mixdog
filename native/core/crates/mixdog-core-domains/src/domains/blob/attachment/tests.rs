/// Names the one attachment `(session, id)` with the given name and type.
struct Names(&'static str, String, Option<String>, Option<String>);

#[async_trait]
impl SessionAttachments for Names {
    async fn named(&self, session_id: &str, id: &str) -> Option<NamedAttachment> {
        (session_id == self.0 && id == self.1)
            .then(|| NamedAttachment { name: self.2.clone(), mime_type: self.3.clone() })
    }
}

fn id_of(bytes: &[u8]) -> String {
    Sha256::digest(bytes).iter().map(|b| format!("{b:02x}")).collect()
}

/// Stores `bytes` under `id` (which a corrupt-file test sets to another blob's id).
fn store_as(dir: &std::path::Path, id: &str, bytes: &[u8]) -> BlobStore {
    let store = BlobStore::new(dir);
    let path = store.path(&format!("sha256:{id}").parse().unwrap());
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, bytes).unwrap();
    store
}

fn source(store: BlobStore, id: &str, name: Option<&str>, mime: Option<&str>) -> Arc<AttachmentSource> {
    let names = Names("s1", id.into(), name.map(Into::into), mime.map(Into::into));
    AttachmentSource::new(store, Arc::new(names), &mixdog_rt::testing::tokens())
}

fn request(id: &str) -> Value {
    json!({ "kind": "attachment", "sessionId": "s1", "attachmentId": id })
}

#[tokio::test]
async fn a_named_attachment_opens_as_a_staged_file_with_its_name_and_type() {
    let dir = tempfile::tempdir().unwrap();
    let id = id_of(b"hello");
    let source = source(store_as(dir.path(), &id, b"hello"), &id, Some("notes"), Some("text/plain"));
    assert_eq!(source.kind(), "attachment");
    let mut opened = source.open(&request(&id), &CancellationToken::new()).await.unwrap();
    let mut text = String::new();
    opened.file.read_to_string(&mut text).unwrap();
    assert_eq!(text, "hello");
    // Node: `attachmentViewName` adds the type's extension to a name without one.
    assert_eq!((opened.name.as_str(), opened.mime_type.as_str()), ("notes.txt", "text/plain"));
    // Staged as Node's `stageTemporaryDownload`: a folder of its own holding the payload; the folder is what goes.
    let staged = opened.cleanup.take().expect("a staged folder");
    assert!(staged.join(mixdog_workspace::transfer::STAGED_PAYLOAD).is_file());
    drop(opened);
    std::fs::remove_dir_all(staged).unwrap();
}

/// The folder and payload are removed whole once dropped: a test's own cleanup.
fn remove_staged(opened: mixdog_workspace::transfer::SourceFile) {
    let folder = opened.cleanup.clone().expect("a staged folder");
    drop(opened);
    std::fs::remove_dir_all(folder).unwrap();
}

#[tokio::test]
async fn a_row_without_a_name_or_type_gets_the_defaults_of_the_transcript_reader() {
    let dir = tempfile::tempdir().unwrap();
    let id = id_of(b"x");
    let source = source(store_as(dir.path(), &id, b"x"), &id, None, None);
    let opened = source.open(&request(&id), &CancellationToken::new()).await.unwrap();
    // `String(info.name || 'attachment')`, `application/octet-stream`; no extension to add.
    assert_eq!((opened.name.as_str(), opened.mime_type.as_str()), ("attachment", "application/octet-stream"));
    remove_staged(opened);
}

/// Generated by running `sanitizedFileName` + `attachmentViewName` (Node 22) on each input.
#[test]
fn view_names_are_what_the_desktop_computed() {
    let long = "x".repeat(130);
    let long_pdf = format!("{}.pdf", "x".repeat(120));
    let cases = [
        ("notes", "text/plain", "notes.txt"),
        ("a/b:c.png", "image/png", "a-b-c.png"),
        ("  ..hidden. ", "text/plain", "hidden.txt"),
        // U+0085 is not JavaScript white space: it stays. U+FEFF is: it goes.
        ("\u{85}x\u{85}", "application/pdf", "\u{85}x\u{85}.pdf"),
        ("\u{feff} x \u{feff}", "image/png", "x.png"),
        ("a**b??.txt", "x/y", "a-b-.txt"),
        ("...", "image/png", "download.png"),
        (long.as_str(), "application/pdf", long_pdf.as_str()),
        ("IMG", "IMAGE/PNG", "IMG.png"),
        ("a.", "text/plain", "a.txt"),
        ("..", "text/plain", "download.txt"),
        ("-a-", "text/plain", "a-.txt"),
    ];
    for (name, mime, expected) in cases {
        assert_eq!(view_name(name, mime), expected, "{name:?} {mime}");
    }
}

#[tokio::test]
async fn every_refusal_is_the_one_the_desktop_threw() {
    let dir = tempfile::tempdir().unwrap();
    let id = id_of(b"hello");
    let cancel = CancellationToken::new();
    let refusal = |result: mixdog_workspace::error::WsResult<mixdog_workspace::transfer::SourceFile>| {
        let error = result.err().expect("a refusal");
        (error.reason, error.message)
    };

    let named = source(store_as(dir.path(), &id, b"hello"), &id, Some("n"), None);
    // An id the transcript does not name (another session's, a guessed hash).
    let other = "a".repeat(64);
    assert_eq!(
        refusal(named.open(&request(&other), &cancel).await),
        (Reason::NotLinked, "This conversation has no such attachment.".into())
    );
    assert_eq!(
        refusal(named.open(&json!({ "kind": "attachment", "sessionId": "s2", "attachmentId": id }), &cancel).await),
        (Reason::NotLinked, "This conversation has no such attachment.".into())
    );
    assert_eq!(Reason::NotLinked.code(), "notLinked");
    // `requiredAttachmentId`: 64 lowercase hex digits, or a TypeError.
    assert_eq!(
        refusal(named.open(&request(&id.to_uppercase()), &cancel).await),
        (Reason::InvalidParams, "attachment id is invalid.".into())
    );
    // `requiredSessionId` (checked before the attachment id) and `requiredAttachmentId`.
    for (source, text) in [
        (json!({ "kind": "attachment", "attachmentId": id }), "session id must be a string."),
        (json!({ "kind": "attachment", "sessionId": 7, "attachmentId": id }), "session id must be a string."),
        (json!({ "kind": "attachment", "sessionId": "  ", "attachmentId": id }), "session id is invalid."),
        (json!({ "kind": "attachment", "sessionId": "a b", "attachmentId": id }), "session id is invalid."),
        (json!({ "kind": "attachment", "sessionId": "s".repeat(257), "attachmentId": id }), "session id is invalid."),
        (json!({ "kind": "attachment", "sessionId": "s1" }), "attachment id is invalid."),
    ] {
        assert_eq!(refusal(named.open(&source, &cancel).await), (Reason::InvalidParams, text.into()), "{source}");
    }
    // The session id is trimmed before it is looked up.
    let trimmed = json!({ "kind": "attachment", "sessionId": " s1\n", "attachmentId": id });
    remove_staged(named.open(&trimmed, &cancel).await.unwrap());
    // Named, but the store lost it.
    let lost_dir = tempfile::tempdir().unwrap();
    let lost = source(BlobStore::new(lost_dir.path()), &id, Some("n"), None);
    assert_eq!(
        refusal(lost.open(&request(&id), &cancel).await),
        (Reason::NotFound, "This attachment is no longer stored on the PC.".into())
    );
    // Bytes that do not hash to the id.
    let bad_dir = tempfile::tempdir().unwrap();
    let corrupt = source(store_as(bad_dir.path(), &id, b"other bytes"), &id, Some("n"), None);
    assert_eq!(
        refusal(corrupt.open(&request(&id), &cancel).await),
        (Reason::Changed, "The stored attachment failed its integrity check.".into())
    );
}
