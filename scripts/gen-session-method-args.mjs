#!/usr/bin/env node
// Writes packages/protocol-client/src/actions/method-args.generated.{mjs,d.mts} from the generated protocol types
// (packages/protocol/src/index.ts). `--check` writes nothing and exits 1 when a committed file differs.
//
// A method is listed when it is a `ClientMethods` entry that the finite session surface exposes as an action
// (`<namespace>/<action>` of action-namespaces.mjs). Per method: `thread` is whether its params type has `threadId`,
// `args` its named params in declared order without `opId` and `threadId`.
import { readFileSync, writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'

const ROOT = new URL('../', import.meta.url)
const PROTOCOL = new URL('packages/protocol/src/index.ts', ROOT)
const NAMESPACES = new URL('packages/protocol-client/src/actions/action-namespaces.mjs', ROOT)
const OUT_DIR = new URL('packages/protocol-client/src/actions/', ROOT)

const HEADER = [
  '// Generated by scripts/gen-session-method-args.mjs from packages/protocol (do not edit).',
  '// Per method: whether it takes `threadId`, and its named params in positional order (without opId/threadId).',
]
const DECLARATION =
  'export const METHOD_ARGS: Readonly<Record<string, { readonly thread: boolean; readonly args: readonly string[] }>>;'

/** Field names of an object type body `{ a: X, b?: Y, }`, in declared order. */
function fieldNames(body) {
  const text = body.replace(/\/\*[\s\S]*?\*\//g, '')
  const names = []
  let depth = 0
  let start = 0
  const take = (end) => {
    const m = /^\s*([A-Za-z_$][\w$]*)\??\s*:/.exec(text.slice(start, end))
    if (m) names.push(m[1])
  }
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (c === '{' || c === '<' || c === '[' || c === '(') depth++
    else if (c === '}' || c === ']' || c === ')') depth--
    else if (c === '>' && text[i - 1] !== '=') depth--
    else if (c === ',' && depth === 0) {
      take(i)
      start = i + 1
    }
  }
  take(text.length)
  return names
}

function paramsOf(source, typeName) {
  const head = `export type ${typeName} = {`
  const at = source.indexOf(head)
  if (at < 0) throw new Error(`protocol type ${typeName} not found`)
  const end = source.indexOf('};\n', at)
  return fieldNames(source.slice(at + head.length, end))
}

export function generate(source, namespaces) {
  const exposed = new Set(Object.entries(namespaces).flatMap(([ns, actions]) => actions.map((a) => `${ns}/${a}`)))
  const start = source.indexOf('export type ClientMethods = {')
  if (start < 0) throw new Error('ClientMethods not found in the protocol types')
  const block = source.slice(start, source.indexOf('\n};', start))
  const rows = []
  for (const [, method, type] of block.matchAll(/^ {2}"([^"]+)": \{ params: (\w+);/gm)) {
    if (!exposed.has(method)) continue
    const fields = paramsOf(source, type)
    rows.push([method, fields.includes('threadId'), fields.filter((f) => f !== 'opId' && f !== 'threadId')])
  }
  rows.sort((a, b) => a[0].localeCompare(b[0], 'en'))
  const lines = rows.map(([m, thread, args]) => `  '${m}': { thread: ${thread}, args: ${JSON.stringify(args)} },`)
  return {
    mjs: [...HEADER, 'export const METHOD_ARGS = Object.freeze({', ...lines, '});', ''].join('\n'),
    dmts: `${DECLARATION}\r\n`,
  }
}

async function main() {
  const check = process.argv.includes('--check')
  const { ACTION_NAMESPACES } = await import(NAMESPACES.href)
  const out = generate(readFileSync(PROTOCOL, 'utf8'), ACTION_NAMESPACES)
  const targets = [
    [new URL('method-args.generated.mjs', OUT_DIR), out.mjs],
    [new URL('method-args.generated.d.mts', OUT_DIR), out.dmts],
  ]
  let drift = false
  for (const [url, text] of targets) {
    let current = null
    try {
      current = readFileSync(url, 'utf8')
    } catch {}
    if (current === text) continue
    drift = true
    if (!check) writeFileSync(url, text)
    else console.error(`${url.pathname} is out of date: run node scripts/gen-session-method-args.mjs`)
  }
  if (check && drift) process.exit(1)
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) await main()
