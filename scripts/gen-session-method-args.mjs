#!/usr/bin/env node
/**
 * Generates src/standalone/protocol-session/method-args.generated.mjs: for every session action routed by
 * action-namespaces.mjs whose method exists in the generated protocol types, the order of its named params, so
 * today's positional action arguments can be sent as named params.
 *
 *   node scripts/gen-session-method-args.mjs          write the file
 *   node scripts/gen-session-method-args.mjs --check  fail when the file is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const TYPES = join(ROOT, 'packages', 'protocol', 'src', 'index.ts');
const OUT = join(ROOT, 'src', 'standalone', 'protocol-session', 'method-args.generated.mjs');

const stripComments = (text) => text.replace(/\/\*[\s\S]*?\*\//g, '');

/** Top-level `name?: type` members of an object type body, in declaration order. */
function members(body) {
  const names = [];
  let depth = 0;
  let start = 0;
  const flush = (end) => {
    const part = body.slice(start, end).trim();
    const match = /^([A-Za-z_][A-Za-z0-9_]*)\??\s*:/.exec(part);
    if (match) names.push(match[1]);
  };
  for (let i = 0; i < body.length; i += 1) {
    const ch = body[i];
    if ('{[(<'.includes(ch)) depth += 1;
    else if ('}])>'.includes(ch) && !(ch === '>' && body[i - 1] === '=')) depth -= 1;
    else if (ch === ',' && depth === 0) {
      flush(i);
      start = i + 1;
    }
  }
  flush(body.length);
  return names;
}

export function methodArgs(source, methods) {
  const clean = stripComments(source);
  const table = /export type ClientMethods = \{([\s\S]*?)\n\};/.exec(clean)[1];
  const paramsType = new Map([...table.matchAll(/"([^"]+)": \{ params: (\w+);/g)].map((m) => [m[1], m[2]]));
  const out = {};
  for (const method of methods) {
    const typeName = paramsType.get(method);
    if (!typeName) continue;
    const declaration = new RegExp(`export type ${typeName} = \\{([\\s\\S]*?)\\};\\n`).exec(clean);
    if (!declaration) continue;
    const fields = members(declaration[1]);
    out[method] = {
      thread: fields.includes('threadId'),
      args: fields.filter((name) => name !== 'opId' && name !== 'threadId'),
    };
  }
  return out;
}

export async function render() {
  const { ACTION_NAMESPACES } = await import(
    pathToFileURL(join(ROOT, 'src', 'standalone', 'protocol-session', 'action-namespaces.mjs')).href
  );
  const methods = Object.entries(ACTION_NAMESPACES).flatMap(([ns, actions]) => actions.map((a) => `${ns}/${a}`));
  const table = methodArgs(readFileSync(TYPES, 'utf8'), methods);
  const rows = Object.entries(table)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([method, { thread, args }]) => `  '${method}': { thread: ${thread}, args: ${JSON.stringify(args)} },`);
  return (
    '// Generated by scripts/gen-session-method-args.mjs from packages/protocol (do not edit).\n' +
    '// Per method: whether it takes `threadId`, and its named params in positional order (without opId/threadId).\n' +
    `export const METHOD_ARGS = Object.freeze({\n${rows.join('\n')}\n});\n`
  );
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const next = await render();
  if (process.argv.includes('--check')) {
    if (readFileSync(OUT, 'utf8') !== next) {
      process.stderr.write('method-args.generated.mjs is stale: run node scripts/gen-session-method-args.mjs\n');
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, next);
  }
}
