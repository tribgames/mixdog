function requireTransport(transport) {
  if (!transport || typeof transport.call !== 'function') {
    throw new TypeError('session transport is invalid');
  }
  return transport;
}

/** Build the one finite client used by TUI, desktop, and in-daemon adapters. */
export function createSessionProtocolClient(rawTransport) {
  const transport = requireTransport(rawTransport);
  const route = (name, params = {}, options = {}) => transport.call(name, params, options);
  return Object.freeze({
    list: (params = {}, options = {}) => route('session.list', params, options),
    create: (params = {}, options = {}) => route('session.create', params, options),
    read: (params = {}, options = {}) => route('session.read', params, options),
    subscribe: (params = {}, options = {}) => route('session.subscribe', params, options),
    unsubscribe: (params = {}, options = {}) => route('session.unsubscribe', params, options),
    submit: (params = {}, options = {}) => route('session.submit', params, options),
    abort: (params = {}, options = {}) => route('session.abort', params, options),
    approve: (params = {}, options = {}) => route('session.approve', params, options),
    configure: (params = {}, options = {}) => route('session.configure', params, options),
    projectList: (params = {}, options = {}) => route('project.list', params, options),
    projectInspect: (params = {}, options = {}) => route('project.inspect', params, options),
    projectAdd: (params = {}, options = {}) => route('project.add', params, options),
    projectTouch: (params = {}, options = {}) => route('project.touch', params, options),
    projectRename: (params = {}, options = {}) => route('project.rename', params, options),
    projectRemove: (params = {}, options = {}) => route('project.remove', params, options),
    projectEnsureDirectory: (params = {}, options = {}) => route('project.ensureDirectory', params, options),
    close: (reason) => Promise.resolve(transport.close?.(reason)),
  });
}
