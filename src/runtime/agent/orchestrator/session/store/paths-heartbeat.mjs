import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, unlinkSync } from 'node:fs';
import * as fsp from 'node:fs/promises';
import { join } from 'node:path';
import { getPluginData } from '../../config.mjs';

// Session file paths are rebuilt on every load/save/sidecar probe. Memoize the
// joined strings per data dir: a changed data dir (MIXDOG_DATA_DIR switch)
// drops the whole memo, and the per-extension maps are bounded.
const SESSION_PATH_MEMO_LIMIT = 4096;
let _memoDataDir = null;
let _memoStoreDir = null;
const _memoFilePaths = new Map(); // extension → Map<id, path>

function _storeDirPath() {
  const dataDir = getPluginData();
  if (dataDir !== _memoDataDir) {
    _memoDataDir = dataDir;
    _memoStoreDir = join(dataDir, 'sessions');
    _memoFilePaths.clear();
  }
  return _memoStoreDir;
}

function _memoFilePath(dir, id, extension) {
  let byId = _memoFilePaths.get(extension);
  if (!byId) {
    byId = new Map();
    _memoFilePaths.set(extension, byId);
  }
  let path = byId.get(id);
  if (path === undefined) {
    path = join(dir, _sessionFileName(id, extension));
    if (byId.size >= SESSION_PATH_MEMO_LIMIT) byId.clear();
    byId.set(id, path);
  }
  return path;
}
export function getStoreDir() {
  const dir = _storeDirPath();
  if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
  return dir;
}
function _sessionFileName(id, extension) {
  return `${id}${extension}`;
}
// Enforce minted session-id shape before using it in a path to prevent
// `../` traversal. session IDs are generated by createSession as
// `sess_<timestamp>_<hex>` — reject anything that doesn't match.
function _assertSessionId(id) {
  if (!id || typeof id !== 'string' || !/^[A-Za-z0-9_-]+$/.test(id)) {
    throw new Error(`[session-store] invalid session id: ${JSON.stringify(id)}`);
  }
}
function _sessionFilePath(id, extension) {
  _assertSessionId(id);
  return _memoFilePath(getStoreDir(), id, extension);
}
export function sessionPath(id) {
  return _sessionFilePath(id, '.json');
}

// ── Sidecar owner-pid helpers ─────────────────────────────
// Liveness sidecars record the publishing process id on their SECOND line so
// a reader can tell a genuinely live owner from a force-killed one whose
// timestamp still looks fresh. Legacy (pid-less) sidecars read back as 0.
export function isProcessAlive(pid) {
  const target = Number(pid) || 0;
  if (target <= 0) return false;
  try {
    process.kill(target, 0);
    return true;
  } catch (error) {
    // ESRCH: no such process. EPERM means the pid exists (alive).
    return error?.code !== 'ESRCH';
  }
}

function _readSidecarOwnerPid(path) {
  try {
    return Number(String(readFileSync(path, 'utf8')).split('\n')[1]) || 0;
  } catch {
    return 0;
  }
}

// ── Heartbeat publish ─────────────────────────────────────
// Lightweight per-session timestamp file (`<id>.hb`) consumed by the
// status aggregator for fresh-session detection. Decoupled from the
// full session JSON save so it can fire at a tight cadence (≤5s)
// without serialising the whole payload. The .hb file holds
// `<msTimestamp>\n<pid>\n` — readers that only need liveness use the file
// mtime, while the attach-on-resume guard verifies the recorded pid.
// Aggregator scans the same sessions/ directory and matches `<id>.hb` to
// `<id>.json`.
const _HEARTBEAT_THROTTLE_MS = 5_000;
const _hbLastAt = new Map();
const _hbOperations = new Map();

function _queueHeartbeatOperation(id, operation) {
  const prior = _hbOperations.get(id) || Promise.resolve();
  const next = prior.then(operation, operation).catch(() => {});
  _hbOperations.set(id, next);
  void next.then(() => {
    if (_hbOperations.get(id) === next) _hbOperations.delete(id);
  });
  return next;
}

function _heartbeatPath(id) {
  return _sessionFilePath(id, '.hb');
}

export function publishHeartbeat(id, ts) {
  if (!id) return Promise.resolve();
  const now = ts || Date.now();
  const last = _hbLastAt.get(id) || 0;
  if (now - last < _HEARTBEAT_THROTTLE_MS) {
    return _hbOperations.get(id) || Promise.resolve();
  }
  const target = _heartbeatPath(id);
  _hbLastAt.set(id, now);
  return _queueHeartbeatOperation(id, () => fsp.writeFile(target, `${now}\n${process.pid}\n`, 'utf8'));
}

export function deleteHeartbeat(id) {
  if (!id) return Promise.resolve();
  // Deleting needs no directory: skip getStoreDir's synchronous probe.
  _assertSessionId(id);
  const target = _memoFilePath(_storeDirPath(), id, '.hb');
  // One ordered async delete behind any pending write for this id. It starts
  // on the next microtask when nothing is pending, so the marker still drops
  // at once, without a synchronous unlink on the turn-settle path. Queuing it
  // (rather than deleting beside the write) keeps a write started just before
  // turn completion from landing after the delete and resurrecting the
  // session's working badge for the full freshness window.
  _hbLastAt.delete(id);
  return _queueHeartbeatOperation(id, () => fsp.unlink(target).catch(() => {}));
}

// Batch reader for session catalogs. Scanning only the handful of `.hb`
// sidecars avoids one failed stat per historical session while still exposing
// cross-process turn activity to desktop/TUI resume lists.
export function listSessionHeartbeatMtimes() {
  const result = new Map();
  try {
    const dir = getStoreDir();
    for (const filename of readdirSync(dir)) {
      if (!filename.endsWith('.hb')) continue;
      const id = filename.slice(0, -3);
      if (!/^[A-Za-z0-9_-]+$/.test(id)) continue;
      try {
        const mtime = statSync(join(dir, filename)).mtimeMs || 0;
        if (mtime > 0) result.set(id, mtime);
      } catch {
        /* sidecar disappeared after readdir */
      }
    }
  } catch {
    /* catalog activity is best-effort */
  }
  return result;
}

// Owner pid recorded in the `<id>.hb` sidecar (0 when absent or written by a
// pre-pid build).
export function readSessionHeartbeatOwnerPid(id) {
  if (!id) return 0;
  try {
    return _readSidecarOwnerPid(_heartbeatPath(id));
  } catch {
    return 0;
  }
}

// A killed owner never deletes its `.hb` sidecar, so bare mtime freshness
// would keep the session "actively driven" for the whole freshness window and
// every cross-open would attach as a viewer whose submits spool to nobody.
// The recorded pid is authoritative proof; pid-less legacy sidecars return
// false (unknown, not dead).
export function isSessionHeartbeatOwnerDead(id) {
  const pid = readSessionHeartbeatOwnerPid(id);
  if (!pid) return false;
  return !isProcessAlive(pid);
}

// ── Interactive presence publish ──────────────────────────
// `<id>.own` marks a live interactive surface (TUI/desktop engine) HOLDING
// the session open — including idle time between turns. Kept separate from
// `.hb` (turn-activity signal consumed by the status aggregator and deleted
// at turn end) so idle presence never fakes a "running" badge. Consumed by
// the attach-on-resume guard (_isActivelyOwnedElsewhere): fresh presence
// means a cross-open must attach as a viewer instead of claiming a second
// writer on the same session file (dual-writer last-save-wins clobbering).
// Refreshed by the engine share tick (~3s call, throttled here) and cleared
// on session switch/dispose; staleness covers crashes.
const _PRESENCE_THROTTLE_MS = 20_000;
const _presenceLastAt = new Map();

function _presencePath(id) {
  return _sessionFilePath(id, '.own');
}

export function publishSessionPresence(id, ts) {
  if (!id) return;
  const now = ts || Date.now();
  const last = _presenceLastAt.get(id) || 0;
  if (now - last < _PRESENCE_THROTTLE_MS) return;
  const target = _presencePath(id);
  _presenceLastAt.set(id, now);
  void fsp.writeFile(target, `${now}\n${process.pid}\n`, 'utf8').catch(() => {});
}

export function deleteSessionPresence(id) {
  if (!id) return;
  try {
    unlinkSync(_presencePath(id));
  } catch {
    /* ignore */
  }
  _presenceLastAt.delete(id);
}

export function readSessionPresenceMtime(id) {
  if (!id) return 0;
  try {
    return statSync(_presencePath(id)).mtimeMs || 0;
  } catch {
    return 0;
  }
}

// A force-killed owner never clears its presence sidecar, so bare mtime
// freshness would lock every resume inside the window into viewer mode with
// nobody draining the shared spool. The `.own` payload records the holder's
// pid; a recorded-but-dead pid is authoritative proof the owner is gone.
export function isSessionPresenceOwnerDead(id) {
  if (!id) return false;
  let pid = 0;
  try {
    pid = _readSidecarOwnerPid(_presencePath(id));
  } catch {
    return false;
  }
  if (!pid) return false;
  return !isProcessAlive(pid);
}
