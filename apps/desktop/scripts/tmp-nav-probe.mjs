import WebSocket from 'ws';
const targets = await (await fetch('http://127.0.0.1:9343/json')).json();
const page = targets.find((t) => t.type === 'page' && !/devtools/i.test(t.url));
const ws = new WebSocket(page.webSocketDebuggerUrl);
await new Promise((res, rej) => { ws.once('open', res); ws.once('error', rej); });
let seq = 0; const pending = new Map();
ws.on('message', (raw) => { const m = JSON.parse(raw.toString()); if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); } });
const send = (method, params = {}) => new Promise((res) => { const id = ++seq; pending.set(id, res); ws.send(JSON.stringify({ id, method, params })); });
const evalJson = async (expr) => (await send('Runtime.evaluate', { expression: expr, returnByValue: true })).result?.result?.value;
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
await send('Emulation.setDeviceMetricsOverride', { width: 484, height: 691, deviceScaleFactor: 0, mobile: false });
await wait(600);
const state = () => evalJson(`JSON.stringify((() => {
  const nav = [...document.querySelectorAll('.titlebar-pane-nav')];
  const count = document.querySelector('.titlebar-pane-count')?.textContent ?? null;
  const active = [...document.querySelectorAll('.pane-carousel-item')].findIndex(el => el.dataset.carouselActive === 'true');
  const toggles = ['.toolbar-sidebar','.toolbar-panel','.toolbar-dock'].map(s => { const el = document.querySelector('.topbar ' + s); const r = el?.getBoundingClientRect(); return el ? Math.round(r.right) : null; });
  return { navButtons: nav.length, count, activeIndex: active, toggleRights: toggles, vw: innerWidth };
})())`);
console.log('before:', await state());
await evalJson(`[...document.querySelectorAll('.titlebar-pane-nav')][1]?.click()`);
await wait(400);
console.log('after next:', await state());
await evalJson(`(() => { const a = document.querySelector('.sidebar.session-sidebar'); if (a?.dataset.state !== 'open') document.querySelector('.toolbar-sidebar')?.click(); })()`);
await wait(500);
console.log('drawer:', await evalJson(`JSON.stringify((() => { const r = document.querySelector('.sidebar.session-sidebar')?.getBoundingClientRect(); return r ? { bottom: Math.round(r.bottom), vh: innerHeight, gap: Math.round(innerHeight - r.bottom) } : null; })())`));
await evalJson(`document.querySelector('.sidebar-backdrop')?.click()`);
await send('Emulation.clearDeviceMetricsOverride');
ws.close();
