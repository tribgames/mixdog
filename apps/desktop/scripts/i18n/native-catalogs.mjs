import { readFileSync } from 'node:fs';
import { catalogState, rendererUrl, bootTemplateUrl, languageRuntime } from './catalog-state.mjs';

const keysUrl = new URL('../../src/shared/native-ui-keys.json', import.meta.url);
export const nativeCatalogUrl = new URL('../../src/shared/native-ui-catalogs.json', import.meta.url);

/** Every language's catalog narrowed to `keys`; a missing entry throws unless allowed. */
function projectCatalogs(catalogs, keys, surface, allowMissing) {
  return Object.fromEntries(
    [...catalogs].map(([language, catalog]) => [
      language,
      Object.fromEntries(
        keys.map((key) => {
          if (!catalog[key] && !allowMissing) throw new Error(`Missing ${surface} translation: ${language}: ${key}`);
          return [key, catalog[key] || ''];
        })
      ),
    ])
  );
}

export function nativeCatalogs({ allowMissing = false, state = catalogState() } = {}) {
  return projectCatalogs(state.catalogs, state.nativeKeys, 'native', allowMissing);
}

export function generatedCatalogs(state, { allowMissing = false } = {}) {
  const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
  const generated = `// Generated by i18n:sync from shared/ui-language.ts. Do not edit.\n${languageRuntime()}`;
  const bootCatalogs = projectCatalogs(state.catalogs, state.bootKeys, 'boot', allowMissing);
  return new Map([
    [keysUrl, json(state.nativeKeys)],
    [nativeCatalogUrl, json(nativeCatalogs({ state, allowMissing }))],
    [new URL('public/ui-language.js', rendererUrl), generated],
    [
      new URL('public/boot.js', rendererUrl),
      `${generated}\nconst BOOT_UI_CATALOGS = ${JSON.stringify(bootCatalogs).replace(/</g, '\\u003c')};\n\n` +
        readFileSync(bootTemplateUrl, 'utf8'),
    ],
  ]);
}
