#!/usr/bin/env node
// Generates `mixdog-browser-policy/src/public_suffix.txt`: the public-suffix trie the Node product's tldts
// (b6f10295a's node_modules, which `getDomain(host, { allowPrivateDomains: true })` of mail-links.mjs reads) holds, one node per
// line, so the core finds a sender's Organizational Domain with the same list. tldts is MIT licensed.
//
//   node benchmarks/rust-core/recorders/gen-public-suffix.mjs <tree with node_modules> <out.txt>
//
// Line: `<root> <flags> <path>`: root `r` (rules) or `x` (exceptions); flags 1 = ICANN, 2 = private (0: a node on the way to a
// rule); path = the node's labels from the right-most one, joined by `/` (empty for the root).
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [tree, out] = process.argv.slice(2);
const require = createRequire(join(tree, 'package.json'));
const trie = require(join(tree, 'node_modules/tldts/dist/cjs/src/data/trie.js'));
const version = JSON.parse(require('node:fs').readFileSync(join(tree, 'node_modules/tldts/package.json'), 'utf8')).version;

// Where each edge's label starts in `labelText`: the edges are stored node by node, in order.
const offsets = new Uint32Array(trie.edgeLength.length);
for (let edge = 0, at = 0; edge < offsets.length; edge += 1) {
  offsets[edge] = at;
  at += trie.edgeLength[edge];
}
const lines = [];
const visit = (root, node, path) => {
  lines.push(`${root} ${trie.nodeFlags[node]} ${path.join('/')}`);
  for (let edge = trie.edgeStart[node]; edge < trie.edgeStart[node + 1]; edge += 1) {
    const label = trie.labelText.slice(offsets[edge], offsets[edge] + trie.edgeLength[edge]);
    visit(root, trie.edgeChild[edge], [...path, label]);
  }
};
visit('r', trie.rulesRoot, []);
visit('x', trie.exceptionsRoot, []);
writeFileSync(out, `# tldts ${version} public-suffix trie (generated by benchmarks/rust-core/recorders/gen-public-suffix.mjs; do not edit)\n${lines.join('\n')}\n`);
console.log(`${lines.length} nodes -> ${out}`);
