#!/usr/bin/env node
// Generates `mixdog-core/src/run_host/turn_reminders/zone_names.rs`: for every zone name the tz database
// (chrono-tz) knows, the name this Node's ICU prints for it (`Intl.DateTimeFormat().resolvedOptions().timeZone`,
// what `localTimestampParts` puts in the current-time reminder). Only the names ICU renames are listed.
//
//   node benchmarks/rust-core/recorders/gen-icu-zone-names.mjs <chrono-tz src/prebuilt/timezones.rs> <out.rs>
import { readFileSync, writeFileSync } from 'node:fs';

const [source, out] = process.argv.slice(2);
const names = [...readFileSync(source, 'utf8').matchAll(/^\s*\("([^"]+)", Tz::/gm)].map((match) => match[1]);
if (names.length < 400) throw new Error(`only ${names.length} zone names read from ${source}`);
const renamed = [];
for (const name of names) {
  const printed = new Intl.DateTimeFormat('en-CA', { timeZone: name }).resolvedOptions().timeZone;
  if (printed !== name) renamed.push([name, printed]);
}
renamed.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
const rows = renamed.map(([name, printed]) => `    ("${name}", "${printed}"),`).join('\n');
writeFileSync(
  out,
  `//! Generated by \`benchmarks/rust-core/recorders/gen-icu-zone-names.mjs\` from chrono-tz's zone names on Node ${process.version} (ICU ${process.versions.icu}, tz ${process.versions.tz}); do not edit.
//!
//! The zone name Node prints for a tz-database name, where ICU's canonical id differs from it; sorted by name.

pub(super) const RENAMED: [(&str, &str); ${renamed.length}] = [
${rows}
];
`
);
console.log(`${names.length} names, ${renamed.length} renamed -> ${out}`);
