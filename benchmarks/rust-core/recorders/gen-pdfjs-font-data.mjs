#!/usr/bin/env node
// Generates the font data of `mixdog-pdf` (native/core/crates/mixdog-pdf/src/fonts/data/*.rs) from pdf.js's own tables:
// the encodings, the Adobe glyph list, the Standard 14 metrics, the font-name maps, the Unicode range and category
// tables and the bidi character types, plus the PDFDocEncoding table of `stringToPDFString`.
//
//   node benchmarks/rust-core/recorders/gen-pdfjs-font-data.mjs --tree <dir holding node_modules/pdfjs-dist 6.4.299>
//
// Like record-media-text.mjs it loads the library from the tree as it is: a module load hook appends exports to
// the source of the legacy `pdf.worker.mjs` in memory, so no byte of the package on disk changes. The output is byte
// stable (a second run writes the same files); the FNV-1a hash of the generated files is written into the
// `GENERATED_FNV1A64` constant of data/mod.rs, which the crate's tests compare against the files.
import { readFileSync, writeFileSync } from 'node:fs';
import { registerHooks } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const PDFJS_VERSION = '6.4.299';
const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const DATA_DIR = join(REPO_ROOT, 'native', 'core', 'crates', 'mixdog-pdf', 'src', 'fonts', 'data');

const treeFlag = process.argv.indexOf('--tree');
const tree = treeFlag > 0 ? process.argv[treeFlag + 1] : null;
if (!tree) throw new Error('usage: gen-pdfjs-font-data.mjs --tree <dir>');
const packageDir = join(tree, 'node_modules', 'pdfjs-dist');
const version = JSON.parse(readFileSync(join(packageDir, 'package.json'), 'utf8')).version;
if (version !== PDFJS_VERSION) throw new Error(`pdfjs-dist ${version} found, ${PDFJS_VERSION} expected`);

const EXPORTS = [
  'ExpertEncoding', 'MacExpertEncoding', 'MacRomanEncoding', 'StandardEncoding', 'WinAnsiEncoding', 'SymbolSetEncoding',
  'ZapfDingbatsEncoding', 'MacStandardGlyphOrdering', 'getGlyphsUnicode', 'getDingbatsGlyphsUnicode', 'getSpecialPUASymbols',
  'UnicodeRanges', 'FontFlags', 'getVerticalPresentationForm', 'getStdFontMap', 'getNonStdFontMap', 'getSerifFonts',
  'getSymbolsFonts', 'getFontNameToFileMap', 'getGlyphMapForMacOrderedFonts', 'getGlyphMapForStandardFonts',
  'getSupplementalGlyphMapForTrebuchetMS', 'getSupplementalGlyphMapForArialBlack', 'getSupplementalGlyphMapForCalibri',
  'getMetrics', 'getSymbolGlyphIdEncoding', 'PDFStringTranslateTable', 'baseTypes', 'arabicTypes', 'normalizeUnicode',
];
registerHooks({
  load(url, context, next) {
    const loaded = next(url, context);
    if (!url.endsWith('/legacy/build/pdf.worker.mjs')) return loaded;
    return { ...loaded, source: `${loaded.source}\nexport { ${EXPORTS.join(', ')} };\n` };
  },
});
const pdfjs = await import(pathToFileURL(join(packageDir, 'legacy', 'build', 'pdf.worker.mjs')).href);

const HEADER = `// Generated by benchmarks/rust-core/recorders/gen-pdfjs-font-data.mjs from pdfjs-dist ${PDFJS_VERSION} (legacy/build/pdf.worker.mjs); do not edit.\n`;

const byBytes = (a, b) => Buffer.compare(Buffer.from(a), Buffer.from(b));
const hex = (n) => `0x${n.toString(16)}`;
function str(s) {
  let out = '"';
  for (const ch of s) {
    const c = ch.codePointAt(0);
    if (ch === '"' || ch === '\\') out += `\\${ch}`;
    else if (c >= 0x20 && c < 0x7f) out += ch;
    else out += `\\u{${c.toString(16)}}`;
  }
  return `${out}"`;
}
const isUint = (v, max) => Number.isInteger(v) && v >= 0 && v <= max;
const need = (cond, what) => {
  if (!cond) throw new Error(`unexpected pdf.js table shape: ${what}`);
};

function stringArray(name, doc, values, length) {
  need(values.length === length, `${name} length ${values.length}`);
  need(values.every((v) => typeof v === 'string'), `${name} holds a non-string`);
  return `/// ${doc}\npub static ${name}: [&str; ${length}] = [\n${values.map((v) => `    ${str(v)},`).join('\n')}\n];\n`;
}
/** `name -> string`, sorted by name (binary search). */
function stringMap(name, doc, table) {
  const entries = Object.entries(table);
  need(entries.every(([, v]) => typeof v === 'string'), `${name} values`);
  entries.sort(([a], [b]) => byBytes(a, b));
  return `/// ${doc}\npub static ${name}: [(&str, &str); ${entries.length}] = [\n${entries.map(([k, v]) => `    (${str(k)}, ${str(v)}),`).join('\n')}\n];\n`;
}
/** The names of a `name -> true` table, sorted. */
function nameSet(name, doc, table) {
  const entries = Object.entries(table);
  need(entries.every(([, v]) => v === true), `${name} values`);
  const keys = entries.map(([k]) => k).sort(byBytes);
  return `/// ${doc}\npub static ${name}: [&str; ${keys.length}] = [\n${keys.map((k) => `    ${str(k)},`).join('\n')}\n];\n`;
}
/** `code -> number`, ascending by code. */
function codeMap(name, doc, table) {
  const entries = Object.entries(table).map(([k, v]) => [Number(k), v]);
  need(entries.every(([k, v]) => isUint(k, 0xffffffff) && isUint(v, 0xffffffff)), `${name} entries`);
  entries.sort(([a], [b]) => a - b);
  return `/// ${doc}\npub static ${name}: [(u32, u32); ${entries.length}] = [\n${entries.map(([k, v]) => `    (${hex(k)}, ${hex(v)}),`).join('\n')}\n];\n`;
}
function ranges(name, doc, test) {
  const out = [];
  let start = -1;
  for (let c = 0; c <= 0x110000; c++) {
    const inSet = c <= 0x10ffff && !(c >= 0xd800 && c <= 0xdfff) && test(String.fromCodePoint(c));
    if (inSet && start < 0) start = c;
    if (!inSet && start >= 0) {
      out.push([start, c - 1]);
      start = -1;
    }
  }
  return `/// ${doc}\npub static ${name}: [(u32, u32); ${out.length}] = [\n${out.map(([a, b]) => `    (${hex(a)}, ${hex(b)}),`).join('\n')}\n];\n`;
}

// ---- encodings.rs
const ENCODINGS = [
  ['STANDARD_ENCODING', 'StandardEncoding'],
  ['MAC_ROMAN_ENCODING', 'MacRomanEncoding'],
  ['WIN_ANSI_ENCODING', 'WinAnsiEncoding'],
  ['MAC_EXPERT_ENCODING', 'MacExpertEncoding'],
  ['SYMBOL_SET_ENCODING', 'SymbolSetEncoding'],
  ['ZAPF_DINGBATS_ENCODING', 'ZapfDingbatsEncoding'],
  ['EXPERT_ENCODING', 'ExpertEncoding'],
];
// getSymbolGlyphIdEncoding is a sparse array (glyph ids 3..191): the holes are "" here, as pdf.js skips them.
const symbolSource = pdfjs.getSymbolGlyphIdEncoding();
const symbolGlyphIds = Array.from({ length: symbolSource.length }, (_, i) => symbolSource[i] ?? '');
let encodings = `${HEADER}//! The simple-font encodings of pdf.js (src/core/encodings.js): code to glyph name, "" where a code has no glyph.\n\n`;
for (const [rustName, jsName] of ENCODINGS) {
  encodings += `\n${stringArray(rustName, `pdf.js \`${jsName}\`.`, pdfjs[jsName], 256)}`;
}
encodings += `\n${stringArray('MAC_STANDARD_GLYPH_ORDERING', 'pdf.js `MacStandardGlyphOrdering`: the glyph names of the 258 standard Macintosh glyph ids.', pdfjs.MacStandardGlyphOrdering, 258)}`;
encodings += `\n${stringArray('SYMBOL_GLYPH_ID_ENCODING', 'pdf.js `getSymbolGlyphIdEncoding()`: the Symbol glyph names by glyph id (ids 0 to 2 have none).', symbolGlyphIds, symbolGlyphIds.length)}`;
encodings += `\n/// pdf.js \`getEncoding(encodingName)\`: the table of a base encoding name, \`None\` for any other name.
pub fn get_encoding(encoding_name: &str) -> Option<&'static [&'static str; 256]> {
    match encoding_name {
${[
  ['WinAnsiEncoding', 'WIN_ANSI_ENCODING'], ['StandardEncoding', 'STANDARD_ENCODING'], ['MacRomanEncoding', 'MAC_ROMAN_ENCODING'],
  ['SymbolSetEncoding', 'SYMBOL_SET_ENCODING'], ['ZapfDingbatsEncoding', 'ZAPF_DINGBATS_ENCODING'], ['ExpertEncoding', 'EXPERT_ENCODING'],
  ['MacExpertEncoding', 'MAC_EXPERT_ENCODING'],
].map(([js, rs]) => `        "${js}" => Some(&${rs}),`).join('\n')}
        _ => None,
    }
}
`;

// ---- glyphlist.rs
function glyphTable(name, doc, table) {
  const entries = Object.entries(table);
  need(entries.every(([, v]) => isUint(v, 0xffffff)), `${name} values`);
  const sorted = [...entries].sort(([a], [b]) => byBytes(a, b));
  return { entries, text: `/// ${doc}\npub static ${name}: [(&str, u32); ${sorted.length}] = [\n${sorted.map(([k, v]) => `    (${str(k)}, ${hex(v)}),`).join('\n')}\n];\n` };
}
const glyphs = glyphTable('GLYPHS_UNICODE', 'pdf.js `getGlyphsUnicode()` (the Adobe glyph list): glyph name to code point, sorted by name.', pdfjs.getGlyphsUnicode());
const dingbats = glyphTable('DINGBATS_GLYPHS_UNICODE', 'pdf.js `getDingbatsGlyphsUnicode()`: ZapfDingbats glyph name to code point, sorted by name.', pdfjs.getDingbatsGlyphsUnicode());
// `recoverGlyphName` walks the table in JavaScript key order (integer-like names first, ascending, then the rest as
// written) and takes the first name with the code point: the first name per code point, in that order.
const firstNameByUnicode = new Map();
for (const [name, unicode] of glyphs.entries) if (!firstNameByUnicode.has(unicode)) firstNameByUnicode.set(unicode, name);
const unicodeNames = [...firstNameByUnicode].sort(([a], [b]) => a - b);
let glyphlist = `${HEADER}//! The Adobe glyph list of pdf.js (src/core/glyphlist.js) and its derived lookups.\n\n`;
glyphlist += `\n${glyphs.text}\n${dingbats.text}`;
glyphlist += `\n/// The glyph name that comes first in pdf.js's key order among the names of \`GLYPHS_UNICODE\` with a code point, sorted by code point.\npub static GLYPH_NAME_BY_UNICODE: [(u32, &str); ${unicodeNames.length}] = [\n${unicodeNames.map(([u, n]) => `    (${hex(u)}, ${str(n)}),`).join('\n')}\n];\n`;
glyphlist += `\n${codeMap('SPECIAL_PUA_SYMBOLS', 'pdf.js `getSpecialPUASymbols()`: private-use code to the code point it stands for.', pdfjs.getSpecialPUASymbols())}`;

// ---- metrics.rs
const flags = pdfjs.FontFlags;
let metrics = `${HEADER}//! The Standard 14 metrics of pdf.js (src/core/metrics.js) and the FontFlags of fonts_utils.js.\n\n`;
metrics += `/// The widths of one Standard 14 font.\n#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub enum Metrics {\n    /// Every glyph has this width (the Courier faces).\n    Fixed(u16),\n    /// Glyph name to width, sorted by name.\n    Glyphs(&'static [(&'static str, u16)]),\n}\n\n`;
metrics += `/// pdf.js \`FontFlags\`.\npub mod font_flags {\n${Object.entries(flags).map(([k, v]) => `    pub const ${k.replace(/([a-z])([A-Z])/g, '$1_$2').toUpperCase()}: u32 = ${v};`).join('\n')}\n}\n\n`;
const metricTable = pdfjs.getMetrics();
const metricBlocks = [];
const metricRows = [];
for (const key of Object.keys(metricTable)) {
  const value = metricTable[key];
  if (typeof value === 'number') {
    need(isUint(value, 0xffff), `metrics ${key}`);
    metricRows.push([key, `    (${str(key)}, Metrics::Fixed(${value})),`]);
    continue;
  }
  need(typeof value === 'function', `metrics ${key}`);
  const widths = Object.entries(value());
  need(widths.every(([, w]) => isUint(w, 0xffff)), `metrics ${key} widths`);
  widths.sort(([a], [b]) => byBytes(a, b));
  const id = `${key.replace(/[^A-Za-z0-9]/g, '_').toUpperCase()}_WIDTHS`;
  metricBlocks.push(`static ${id}: [(&str, u16); ${widths.length}] = [\n${widths.map(([n, w]) => `    (${str(n)}, ${w}),`).join('\n')}\n];\n`);
  metricRows.push([key, `    (${str(key)}, Metrics::Glyphs(&${id})),`]);
}
metricRows.sort(([a], [b]) => byBytes(a, b));
metrics += `${metricBlocks.join('\n')}\n/// pdf.js \`getMetrics()\`: the Standard 14 font name to its widths, sorted by name.\npub static METRICS: [(&str, Metrics); ${metricRows.length}] = [\n${metricRows.map(([, row]) => row).join('\n')}\n];\n`;

// ---- standard_fonts.rs
let standard = `${HEADER}//! The font-name maps and standard-font glyph maps of pdf.js (src/core/standard_fonts.js, fonts.js).\n\n`;
standard += `\n${stringMap('STD_FONT_MAP', 'pdf.js `getStdFontMap()`: a font name spelling to the Standard 14 name, sorted by spelling.', pdfjs.getStdFontMap())}`;
standard += `\n${stringMap('NON_STD_FONT_MAP', 'pdf.js `getNonStdFontMap()`: a font name to the Standard 14 face it is drawn with, sorted by name.', pdfjs.getNonStdFontMap())}`;
standard += `\n${nameSet('SERIF_FONTS', 'The names of pdf.js `getSerifFonts()`, sorted.', pdfjs.getSerifFonts())}`;
standard += `\n${nameSet('SYMBOLS_FONTS', 'The names of pdf.js `getSymbolsFonts()`, sorted.', pdfjs.getSymbolsFonts())}`;
standard += `\n${stringMap('FONT_NAME_TO_FILE', 'pdf.js `getFontNameToFileMap()`: a Standard 14 name to the file of its bundled font program, sorted by name.', pdfjs.getFontNameToFileMap())}`;
standard += `\n${codeMap('GLYPH_MAP_FOR_MAC_ORDERED_FONTS', 'pdf.js `getGlyphMapForMacOrderedFonts()`: glyph id to code point, ascending by id.', pdfjs.getGlyphMapForMacOrderedFonts())}`;
standard += `\n${codeMap('GLYPH_MAP_FOR_STANDARD_FONTS', 'pdf.js `getGlyphMapForStandardFonts()`: glyph id to code point, ascending by id.', pdfjs.getGlyphMapForStandardFonts())}`;
standard += `\n${codeMap('SUPPLEMENTAL_GLYPH_MAP_FOR_TREBUCHET_MS', 'pdf.js `getSupplementalGlyphMapForTrebuchetMS()`: glyph id to code point, ascending by id.', pdfjs.getSupplementalGlyphMapForTrebuchetMS())}`;
standard += `\n${codeMap('SUPPLEMENTAL_GLYPH_MAP_FOR_ARIAL_BLACK', 'pdf.js `getSupplementalGlyphMapForArialBlack()`: glyph id to code point, ascending by id.', pdfjs.getSupplementalGlyphMapForArialBlack())}`;
standard += `\n${codeMap('SUPPLEMENTAL_GLYPH_MAP_FOR_CALIBRI', 'pdf.js `getSupplementalGlyphMapForCalibri()`: glyph id to code point, ascending by id.', pdfjs.getSupplementalGlyphMapForCalibri())}`;

// ---- unicode.rs
const nfkcSet = [];
for (let c = 0; c <= 0xffff; c++) {
  if (c >= 0xd800 && c <= 0xdfff) continue;
  const ch = String.fromCharCode(c);
  if (pdfjs.normalizeUnicode(ch) !== ch) nfkcSet.push(ch);
}
// normalizeUnicode normalises each run of its character class as a whole; the Rust port maps character by character,
// which is the same when no pair of characters of the class combines or reorders across the join.
for (const a of nfkcSet) {
  for (const b of nfkcSet) {
    need(`${a}${b}`.normalize('NFKC') === a.normalize('NFKC') + b.normalize('NFKC'), `NFKC of a run (${a.codePointAt(0).toString(16)}, ${b.codePointAt(0).toString(16)})`);
  }
}
// U+FB05 is the one character the function rewrites by a map (to U+017F U+0074), not by NFKC.
const fb05 = nfkcSet.indexOf('ﬅ');
need(fb05 >= 0 && pdfjs.normalizeUnicode('ﬅ') === 'ſt', 'normalizeUnicode ufb05');
nfkcSet.splice(fb05, 1);
need(nfkcSet.every((ch) => pdfjs.normalizeUnicode(ch) === ch.normalize('NFKC')), 'normalizeUnicode is NFKC');
const vertical = pdfjs.getVerticalPresentationForm();
let unicode = `${HEADER}//! The Unicode tables of pdf.js (src/core/unicode.js, core_utils.js, bidi.js, util.js) and the property tables its regular expressions use.\n\n`;
unicode += `\n/// pdf.js \`UnicodeRanges\`: the OS/2 ulUnicodeRange bit \`i\` is set for code points inside any (first, last) pair of entry \`i\`.\npub static UNICODE_RANGES: [&[u32]; ${pdfjs.UnicodeRanges.length}] = [\n${pdfjs.UnicodeRanges.map((r) => `    &[${r.map(hex).join(', ')}],`).join('\n')}\n];\n`;
unicode += `\n${codeMap('VERTICAL_PRESENTATION_FORM', 'pdf.js `getVerticalPresentationForm()`: a code point to its vertical presentation form, ascending.', vertical)}`;
unicode += `\n/// The characters \`normalizeUnicode\` rewrites by NFKC and their NFKC form, ascending (its character class, \`U+FB05\` apart).\npub static NFKC_NORMALIZED: [(char, &str); ${nfkcSet.length}] = [\n${nfkcSet.map((ch) => `    ('\\u{${ch.codePointAt(0).toString(16)}}', ${str(ch.normalize('NFKC'))}),`).join('\n')}\n];\n`;
unicode += `\n${ranges('NONSPACING_MARKS', 'The code points of the general category Mn (`\\p{Mn}`), as inclusive ranges.', (ch) => /^\p{Mn}$/u.test(ch))}`;
unicode += `\n${ranges('FORMAT_CHARS', 'The code points of the general category Cf (`\\p{Cf}`), as inclusive ranges.', (ch) => /^\p{Cf}$/u.test(ch))}`;
for (const [rustName, jsName] of [['BIDI_BASE_TYPES', 'baseTypes'], ['BIDI_ARABIC_TYPES', 'arabicTypes']]) {
  const values = pdfjs[jsName];
  need(values.length === 256 && values.every((v) => typeof v === 'string'), jsName);
  unicode += `\n/// pdf.js bidi \`${jsName}\`: the character type of the code points ${jsName === 'baseTypes' ? 'U+0000 to U+00FF' : 'U+0600 to U+06FF (by the low byte)'}.\npub static ${rustName}: [&str; 256] = [\n${values.map((v) => `    ${str(v)},`).join('\n')}\n];\n`;
}

// ---- pdfdoc.rs
const translate = pdfjs.PDFStringTranslateTable;
need(translate.length === 161 && translate.every((v) => isUint(v, 0xffff)), 'PDFStringTranslateTable');
const pdfdoc = `${HEADER}//! The PDFDocEncoding differences of pdf.js \`stringToPDFString\` (src/shared/util.js).\n\n\n/// Byte to the character it stands for where PDFDocEncoding differs from Latin-1, 0 where it does not (bytes 0 to 160).\npub static PDF_STRING_TRANSLATE_TABLE: [u16; 161] = [\n${translate.map((v) => `    ${v === 0 ? '0' : hex(v)},`).join('\n')}\n];\n`;

// ---- write
const files = { 'encodings.rs': encodings, 'glyphlist.rs': glyphlist, 'metrics.rs': metrics, 'standard_fonts.rs': standard, 'unicode.rs': unicode, 'pdfdoc.rs': pdfdoc };
let hash = 0xcbf29ce484222325n;
for (const [name, text] of Object.entries(files)) {
  const body = text.replace(/\r/g, '');
  for (const b of Buffer.from(body)) hash = ((hash ^ BigInt(b)) * 0x100000001b3n) & 0xffffffffffffffffn;
  writeFileSync(join(DATA_DIR, name), body);
}
const hashText = hash.toString(16).padStart(16, '0');
const modPath = join(DATA_DIR, 'mod.rs');
const mod = readFileSync(modPath, 'utf8');
const updated = mod.replace(/pub const GENERATED_FNV1A64: &str = "[0-9a-f]*";/, `pub const GENERATED_FNV1A64: &str = "${hashText}";`);
need(updated.includes(`"${hashText}"`), 'GENERATED_FNV1A64 constant in data/mod.rs');
writeFileSync(modPath, updated);
console.log(`pdf.js ${version}: ${Object.keys(files).length} files, hash ${hashText}`);
