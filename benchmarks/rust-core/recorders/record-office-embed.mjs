const recordFace = async (entry) => {
  const document = await PDFDocument.create();
  document.registerFontkit(fontkit);
  const font = await document.embedFont(faceBytes(entry.face), { subset: true });
  const steps = [];
  for (const text of entry.texts) {
    steps.push({
      text,
      covers: fonts.fontCovers(font, text),
      widths: Object.fromEntries(SIZES.map((size) => [String(size), font.widthOfTextAtSize(text, size)])),
      encoded: font.encodeText(text).asString(),
    });
  }
  const heights = { plain: font.heightAtSize(12), noDescender: font.heightAtSize(12, { descender: false }), sizeAtHeight: font.sizeAtHeight(100) };
  await document.save({ useObjectStreams: false, addDefaultPage: false });
  const context = document.context;
  const fontDict = context.lookup(font.ref);
  const cidRef = fontDict.get(PDFName.of('DescendantFonts')).asArray()[0];
  const cid = context.lookup(cidRef);
  const descriptor = context.lookup(cid.get(PDFName.of('FontDescriptor')));
  const programKey = descriptor.has(PDFName.of('FontFile2')) ? 'FontFile2' : 'FontFile3';
  const program = streamBytes(context, descriptor.get(PDFName.of(programKey)));
  // the glyphs of the subset in order (original glyph ids, .notdef first): the encoded ones, then the components of composite glyphs
  const subsetGlyphs = font.embedder.subset.glyphs.slice();
  return {
    name: entry.name,
    encodedGlyphs: subsetGlyphs.slice(0, 1 + font.embedder.glyphs.length),
    subsetGlyphs,
    face: entry.face,
    fontName: font.name,
    steps,
    heights,
    fontDict: dump(context, fontDict),
    program: programKey === 'FontFile2' ? { kind: 'glyf', ...sfntSummary(program) } : { kind: 'cff', ...cffSummary(program) },
    toUnicode: Buffer.from(streamBytes(context, fontDict.get(PDFName.of('ToUnicode')))).toString('latin1'),
  };
};

