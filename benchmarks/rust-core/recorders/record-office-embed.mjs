// A pdf-lib object as JSON. A reference is followed; a stream is its dictionary and the hash and length of its decoded bytes.
const dump = (context, object) => {
  if (object instanceof PDFRef) return dump(context, context.lookup(object));
  if (object instanceof PDFName) return { name: object.decodeText() };
  if (object instanceof PDFNumber) return object.asNumber();
  if (object instanceof PDFString || object instanceof PDFHexString) return { string: object.decodeText() };
  if (object instanceof PDFArray) return object.asArray().map((item) => dump(context, item));
  if (object instanceof PDFRawStream) {
    const bytes = decodePDFRawStream(object).decode();
    return { dict: dump(context, object.dict), length: bytes.length, sha256: sha(bytes) };
  }
  if (object instanceof PDFDict) {
    const out = {};
    for (const [key, value] of object.entries()) out[key.decodeText()] = dump(context, value);
    return out;
  }
  return String(object);
};

