// ---- the subset font programs ----------------------------------------------------------------------------------------------

const u16 = (bytes, at) => (bytes[at] << 8) | bytes[at + 1];
const u32 = (bytes, at) => ((bytes[at] << 24) | (bytes[at + 1] << 16) | (bytes[at + 2] << 8) | bytes[at + 3]) >>> 0;
const i16 = (bytes, at) => (u16(bytes, at) << 16) >> 16;

const sfntSummary = (bytes) => {
  const count = u16(bytes, 4);
  const tables = {};
  for (let index = 0; index < count; index += 1) {
    const at = 12 + index * 16;
    const tag = String.fromCharCode(...bytes.subarray(at, at + 4));
    tables[tag] = { offset: u32(bytes, at + 8), length: u32(bytes, at + 12) };
  }
  const slice = (tag) => bytes.subarray(tables[tag].offset, tables[tag].offset + tables[tag].length);
  const head = slice('head');
  const hhea = slice('hhea');
  const loca = slice('loca');
  const hmtx = slice('hmtx');
  const glyf = slice('glyf');
  const glyphs = u16(slice('maxp'), 4);
  const long = i16(head, 50) === 1;
  const offsets = [];
  for (let index = 0; index <= glyphs; index += 1) offsets.push(long ? u32(loca, index * 4) : u16(loca, index * 2) * 2);
  const metrics = u16(hhea, 34);
  const out = {
    tableTags: Object.keys(tables),
    glyphCount: glyphs,
    longLoca: long,
    glyphs: [],
    advances: [],
    bearings: [],
    tableData: Object.fromEntries(['cvt ', 'prep', 'fpgm'].filter((tag) => tables[tag]).map((tag) => [tag, b64(slice(tag))])),
  };
  for (let index = 0; index < glyphs; index += 1) {
    out.glyphs.push({ length: offsets[index + 1] - offsets[index], data: b64(glyf.subarray(offsets[index], offsets[index + 1])) });
    const at = Math.min(index, metrics - 1) * 4;
    out.advances.push(u16(hmtx, at));
    out.bearings.push(index < metrics ? i16(hmtx, at + 2) : i16(hmtx, metrics * 4 + (index - metrics) * 2));
  }
  out.numberOfMetrics = metrics;
  return out;
};

// A CFF reader of just what the summary needs: INDEX, DICT, the Top DICT, FDArray and the Private DICTs.
const cffSummary = (bytes) => {
  const readIndex = (at) => {
    const count = u16(bytes, at);
    if (count === 0) return { items: [], end: at + 2 };
    const size = bytes[at + 2];
    const offset = (index) => {
      let value = 0;
      for (let i = 0; i < size; i += 1) value = value * 256 + bytes[at + 3 + index * size + i];
      return value;
    };
    const base = at + 3 + (count + 1) * size - 1;
    const items = [];
    for (let index = 0; index < count; index += 1) items.push(bytes.subarray(base + offset(index), base + offset(index + 1)));
    return { items, end: base + offset(count) };
  };
  const readDict = (data) => {
    const entries = {};
    let operands = [];
    for (let at = 0; at < data.length; ) {
      const b0 = data[at];
      if (b0 <= 21) {
        const op = b0 === 12 ? 1200 + data[at + 1] : b0;
        at += b0 === 12 ? 2 : 1;
        entries[op] = operands;
        operands = [];
      } else if (b0 === 28) { operands.push(i16(data, at + 1)); at += 3; }
      else if (b0 === 29) { operands.push(u32(data, at + 1) | 0); at += 5; }
      else if (b0 === 30) {
        at += 1;
        while (true) { const byte = data[at++]; if ((byte & 15) === 15 || byte >> 4 === 15) break; }
        operands.push(0);
      } else if (b0 <= 246) { operands.push(b0 - 139); at += 1; }
      else if (b0 <= 250) { operands.push((b0 - 247) * 256 + data[at + 1] + 108); at += 2; }
      else { operands.push(-(b0 - 251) * 256 - data[at + 1] - 108); at += 2; }
    }
    return entries;
  };
  const names = readIndex(bytes[2]);
  const top = readIndex(names.end);
  const strings = readIndex(top.end);
  const globals = readIndex(strings.end);
  const topDict = readDict(top.items[0]);
  const charStrings = readIndex(topDict[17][0]);
  const privateOf = (dict) => {
    if (!dict[18]) return null;
    const [size, offset] = dict[18];
    const entries = readDict(bytes.subarray(offset, offset + size));
    const subrs = entries[19] ? readIndex(offset + entries[19][0]).items.map((item) => b64(item)) : [];
    return { subrs, defaultWidthX: entries[20]?.[0] ?? null, nominalWidthX: entries[21]?.[0] ?? null };
  };
  const fdArray = topDict[1236] ? readIndex(topDict[1236][0]).items.map((item) => privateOf(readDict(item))) : [privateOf(topDict)];
  return {
    cid: Boolean(topDict[1230]),
    charStrings: charStrings.items.map((item) => b64(item)),
    charStringLengths: charStrings.items.map((item) => item.length),
    globalSubrs: globals.items.map((item) => b64(item)),
    fontDicts: fdArray,
    strings: strings.items.map((item) => Buffer.from(item).toString('latin1')),
    topOperators: Object.keys(topDict).map(Number).sort((a, b) => a - b),
    cidCount: topDict[1234]?.[0] ?? null,
    fdSelectPresent: Boolean(topDict[1237]),
    charsetPresent: Boolean(topDict[15]),
  };
};

