#!/usr/bin/env node
// What pdf-lib 1.17.1 with @pdf-lib/fontkit 1.1.1 does to the fonts of the office PDF writers
// (src/runtime/office/pdf/pdf-fonts.mjs, pdf-writer.mjs, pdf-forms.mjs), for the Rust module mixdog_pdf::embed
// (crates/mixdog-pdf/tests/twin_embed.rs replays it):
//   faces       TrueType (glyf, with composite glyphs) and OpenType (CFF) faces of the repository's own fixtures
//               (office-measure/faces and office-glyphs/fonts) embedded as subsets; texts are encoded and measured, and
//               after a save the objects pdf-lib wrote are recorded: the Type0 font, CIDFont (Subtype, W), descriptor
//               (Flags, FontBBox, Ascent, ...), the ToUnicode CMap text, and what the subset font program holds (the
//               glyph order, the hash of every glyf slice or charstring and subroutine, the advances)
//   standard    the 14 standard fonts: the codes, widths with kerning, heights, the dictionary, and the refusal text
//   documentFont  pdf-fonts.mjs itself (embedDocumentFont, embedBoldFont, fontCovers, unicodeFontPath) with explicit
//               fonts, the MIXDOG_OCR_FONT override and no system font (process.platform is set to an unknown
//               platform while the module loads, so the machine's own fonts take no part), with the font path replaced
//               by <font> in every message
//
//   node benchmarks/rust-core/recorders/record-office-embed.mjs --tree <product tree with node_modules> [--faces <fixtures root>]
//   node benchmarks/rust-core/recorders/record-office-embed.mjs --tree <tree> --standard-data
//   node benchmarks/rust-core/recorders/record-office-embed.mjs --tree <tree> --verify <dir>
//
// Output: native/core/fixtures/office-embed/golden.json (and its MANIFEST.json). --faces names the directory that holds
// office-measure/faces and office-glyphs/fonts (default: the fixtures root of this checkout). With --standard-data the
// recorder only writes native/core/crates/mixdog-pdf/src/embed/standard_data.txt (the AFM widths, kerning, metrics and
// the three encodings of @pdf-lib/standard-fonts). With --verify the recorder only prints, as JSON on standard output,
// the text and the widths pdf.js reads from every .pdf file in <dir> (the live test has pdf.js read what Rust wrote).
// The product tree is only read.
